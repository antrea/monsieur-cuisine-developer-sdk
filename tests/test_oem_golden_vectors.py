"""SDK MCC codec and host rules against vectors produced by the OEM app's own code.

``fixtures/oem/mcc_292_vectors.jsonl`` was generated by executing, on a
plain JVM, the PowerBoard / CookingUtils / Limits bytecode of de.silpion.mc2
build 292 taken from a device owner's eMMC backup (see the fixture README).
It holds inputs and outputs only; no OEM code is part of this repository.
"""
import json
import unittest
from pathlib import Path

from monsieur_cuisine_sdk.conformance import compare, compare_tx, compare_rx

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures" / "oem" / "mcc_292_vectors.jsonl"


def load_vectors(path=FIXTURE):
    with path.open("rt", encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


class OemGoldenVectors(unittest.TestCase):
    def test_fixture_present_and_covers_every_kind(self):
        kinds = {v["kind"] for v in load_vectors()}
        self.assertEqual(kinds, {"tx", "rx", "celsius", "level", "time_limit", "rpm_level"})

    def test_sdk_matches_every_oem_vector(self):
        failures = []
        for number, vector in enumerate(load_vectors()):
            for problem in compare(vector):
                failures.append(f"#{number} {vector['kind']}: {problem}")
        self.assertEqual(failures[:20], [], f"{len(failures)} disagreements")


if __name__ == "__main__":
    unittest.main()
