"""Native reference tool input/result gates, NOT an OEM execution fixture."""
from copy import deepcopy
import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import zipfile

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("native_reference_tool", ROOT / "tools/verify_oem_native.py")
tool = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tool)


class NativeReferenceGates(unittest.TestCase):
    def test_physical_targets_are_rejected_before_any_tool_or_file_access(self):
        with patch.object(tool.subprocess, "run") as executed:
            with self.assertRaises(ValueError):
                tool.verify("absent.apk", "absent-probe.apk", adb="adb", serial="physical-target",
                            server_port=5039, workdir="unused")
            executed.assert_not_called()

    def test_unidentified_dex_or_native_bytes_never_reach_the_emulator(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            original = root / "synthetic.apk"
            with zipfile.ZipFile(original, "w") as output:
                output.writestr("classes.dex", b"synthetic input, not an OEM reference")
                output.writestr("lib/x86/libserial_port.so", b"synthetic native bytes")
            with patch.object(tool.subprocess, "run") as executed:
                with self.assertRaises(ValueError):
                    tool.verify(original, "probe.apk", adb="adb", serial="emulator-5580",
                                server_port=5039, workdir=root / "output")
                executed.assert_not_called()
            self.assertFalse((root / "output").exists())

    def test_result_contract_does_not_accept_partial_checks_or_hardware_claims(self):
        # Synthetic contract data only: the actual original JNI has a separate
        # emulator execution report and is never generated by this test.
        result = {"passed": True, "software_pty_only": True, "endpoint": "/dev/ptmx", "android_api": 23,
                  "abi": "x86", "character_device": True, "probe_cleanup_verified_ebadf": True,
                  "native_open_verified": True, "original_native_close_invoked": False,
                  "original_native_close_verified": False, "original_descriptor_field": "a",
                  "original_native_close_required_field": "mFd", "original_native_close_field_present": False,
                  "invalid_baud_rejected": True, "open_baud_argument": 4800, "physical_baud_measured": False,
                  "payload_bytes_sent": 0, "hardware_verified": False,
                  "original_dex_sha256": tool.DEX_SHA, "original_native_sha256": tool.NATIVE_SHA}
        tool.validate_result(result)
        for key, value in (("probe_cleanup_verified_ebadf", False), ("hardware_verified", True),
                           ("original_native_close_verified", True), ("original_native_close_invoked", True),
                           ("payload_bytes_sent", False), ("original_native_sha256", "0" * 64)):
            invalid = deepcopy(result); invalid[key] = value
            with self.assertRaises(ValueError):
                tool.validate_result(invalid)
